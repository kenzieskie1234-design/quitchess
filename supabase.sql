-- Quiet Move Chess social features
-- Run this entire script in Supabase SQL Editor.
-- Prototype identity currently uses a browser-generated player_id. This is NOT secure account authentication.

create table if not exists public.profiles (
  player_id text primary key,
  username text not null unique,
  bio text not null default '',
  elo integer not null default 400,
  last_seen timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.friend_requests (
  id bigint generated by default as identity primary key,
  from_id text not null references public.profiles(player_id) on delete cascade,
  to_id text not null references public.profiles(player_id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','declined')),
  created_at timestamptz not null default now(),
  check (from_id <> to_id)
);

create table if not exists public.friendships (
  player_a text not null references public.profiles(player_id) on delete cascade,
  player_b text not null references public.profiles(player_id) on delete cascade,
  status text not null default 'accepted' check (status in ('accepted')),
  created_at timestamptz not null default now(),
  primary key (player_a, player_b),
  check (player_a < player_b)
);

create table if not exists public.duel_requests (
  id bigint generated by default as identity primary key,
  from_id text not null references public.profiles(player_id) on delete cascade,
  to_id text not null references public.profiles(player_id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','declined')),
  time_control text not null default '10+0',
  room_id text,
  created_at timestamptz not null default now(),
  check (from_id <> to_id)
);

alter table public.chess_rooms add column if not exists result text;
alter table public.chess_rooms add column if not exists completed_at timestamptz;

alter table public.profiles enable row level security;
alter table public.friend_requests enable row level security;
alter table public.friendships enable row level security;
alter table public.duel_requests enable row level security;
alter table public.chess_rooms enable row level security;

