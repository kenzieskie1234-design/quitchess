-- Quick matchmaking queue
create table if not exists public.matchmaking_queue (
  id bigint generated by default as identity primary key,
  player_id text not null,
  status text not null default 'waiting' check (status in ('waiting','matched')),
  room_id text,
  matched_with text,
  created_at timestamptz not null default now()
);
alter table public.matchmaking_queue enable row level security;
drop policy if exists "matchmaking queue demo access" on public.matchmaking_queue;
create policy "matchmaking queue demo access" on public.matchmaking_queue
  for all to anon, authenticated using (true) with check (true);
create index if not exists matchmaking_waiting_created
  on public.matchmaking_queue (status, created_at);
create index if not exists matchmaking_player_status
  on public.matchmaking_queue (player_id, status);
