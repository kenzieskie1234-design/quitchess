-- Two-hour Quiet Move Blitz tournament lobby and trophy records.
create table if not exists public.qm_tournaments (
  id text primary key,
  starts_at timestamptz not null,
  status text not null default 'registration'
    check (status in ('registration','running','completed')),
  created_at timestamptz not null default now()
);
create table if not exists public.qm_tournament_entries (
  id bigint generated by default as identity primary key,
  tournament_id text not null references public.qm_tournaments(id) on delete cascade,
  player_id text not null references public.profiles(player_id) on delete cascade,
  username text not null,
  elo integer not null default 400,
  created_at timestamptz not null default now(),
  unique (tournament_id, player_id)
);
create table if not exists public.qm_tournament_trophies (
  id bigint generated by default as identity primary key,
  tournament_id text not null references public.qm_tournaments(id) on delete cascade,
  player_id text not null references public.profiles(player_id) on delete cascade,
  placement integer not null default 1,
  awarded_at timestamptz not null default now(),
  unique (tournament_id, player_id)
);
alter table public.qm_tournaments enable row level security;
alter table public.qm_tournament_entries enable row level security;
alter table public.qm_tournament_trophies enable row level security;
