create policy "friend requests demo access" on public.friend_requests for all to anon, authenticated using (true) with check (true);
drop policy if exists "friendships demo access" on public.friendships;
create policy "friendships demo access" on public.friendships for all to anon, authenticated using (true) with check (true);
drop policy if exists "duel requests demo access" on public.duel_requests;
create policy "duel requests demo access" on public.duel_requests for all to anon, authenticated using (true) with check (true);

